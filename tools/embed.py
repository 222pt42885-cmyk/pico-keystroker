#!/usr/bin/env python3
"""Embed config/input.txt + config/config.ini into a C header.

Reads the typed payload and the INI configuration and emits them as
`static const unsigned char` byte arrays (plus lengths) so firmware can
compile them in without a filesystem.

Usage:
    python3 tools/embed.py --input config/input.txt \\
        --config config/config.ini --output generated/payload.h
"""

import argparse
import datetime
import os
import sys


def read_bytes(path):
    with open(path, "rb") as f:
        return f.read()


def format_array(data, indent="    "):
    lines = []
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append(indent + ", ".join("0x%02x" % b for b in chunk) + ",")
    if not lines:
        lines.append(indent + "0x00, /* empty */")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Embed payload + config files as C byte arrays.")
    parser.add_argument("--input", required=True,
                        help="path to the typed payload text file")
    parser.add_argument("--config", required=True,
                        help="path to the INI config file")
    parser.add_argument("--output", required=True,
                        help="path of the generated C header")
    args = parser.parse_args(argv)

    try:
        payload = read_bytes(args.input)
    except OSError as exc:
        print("embed: cannot read --input %s: %s" % (args.input, exc),
              file=sys.stderr)
        return 1
    try:
        config = read_bytes(args.config)
    except OSError as exc:
        print("embed: cannot read --config %s: %s" % (args.config, exc),
              file=sys.stderr)
        return 1

    stamp = datetime.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")
    header = (
        "/* Auto-generated by tools/embed.py on %s -- do not edit.\n"
        " * Sources: %s (%d bytes), %s (%d bytes).\n"
        " * Both arrays carry an extra trailing NUL so they can also be\n"
        " * used as C strings; *_len counts payload bytes excluding NUL.\n"
        " */\n"
        "#pragma once\n"
        "\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "\n"
        "static const unsigned char keystroker_payload_text[] = {\n"
        "%s\n"
        "    0x00\n"
        "};\n"
        "static const size_t keystroker_payload_text_len = sizeof(keystroker_payload_text) - 1u;\n"
        "\n"
        "static const unsigned char keystroker_config_text[] = {\n"
        "%s\n"
        "    0x00\n"
        "};\n"
        "static const size_t keystroker_config_text_len = sizeof(keystroker_config_text) - 1u;\n"
        % (stamp, args.input, len(payload), args.config, len(config),
           format_array(payload), format_array(config))
    )

    out_dir = os.path.dirname(os.path.abspath(args.output))
    if out_dir and not os.path.isdir(out_dir):
        os.makedirs(out_dir)
    try:
        with open(args.output, "w", newline="\n") as f:
            f.write(header)
    except OSError as exc:
        print("embed: cannot write --output %s: %s" % (args.output, exc),
              file=sys.stderr)
        return 1
    print("embed: wrote %s (payload=%d bytes, config=%d bytes)"
          % (args.output, len(payload), len(config)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
